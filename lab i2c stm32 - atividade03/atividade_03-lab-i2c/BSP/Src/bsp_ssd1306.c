/** @brief Envia uma pagina do framebuffer (posiciona o cursor e manda 128 bytes). */
static bool send_page(uint8_t page)
{
    const uint8_t cmd[3] = {
        (uint8_t)(0xB0U | page),                          /* pagina          */
        (uint8_t)(0x00U | (BSP_SSD1306_X_OFFSET & 0x0FU)),/* coluna, nibble L */
        (uint8_t)(0x10U | (BSP_SSD1306_X_OFFSET >> 4))    /* coluna, nibble H */
    };

    if (!bsp_i2c_write_reg(BSP_SSD1306_ADDR, CTRL_CMD, cmd, sizeof(cmd)))
    {
        return false;
    }
    return bsp_i2c_write_reg(BSP_SSD1306_ADDR, CTRL_DATA, s_fb[page],
                             BSP_SSD1306_WIDTH);
}

bool bsp_ssd1306_init(void)
{
    s_page = 0U;
    bsp_ssd1306_clear();

    if (!bsp_i2c_is_ready(BSP_SSD1306_ADDR))
    {
        return false;
    }
    if (!bsp_i2c_write_reg(BSP_SSD1306_ADDR, CTRL_CMD, s_init_seq,
                           sizeof(s_init_seq)))
    {
        return false;
    }
    return bsp_ssd1306_update();
}

void bsp_ssd1306_clear(void)
{
    memset(s_fb, 0, sizeof(s_fb));
}

void bsp_ssd1306_pixel(int x, int y, bool on)
{
    if ((x < 0) || (x >= BSP_SSD1306_WIDTH) || (y < 0) || (y >= BSP_SSD1306_HEIGHT))
    {
        return;
    }
    if (on)
    {
        s_fb[y >> 3][x] |= (uint8_t)(1U << (y & 7));
    }
    else
    {
        s_fb[y >> 3][x] &= (uint8_t)~(1U << (y & 7));
    }
}

void bsp_ssd1306_line(int x0, int y0, int x1, int y1)
{
    int dx  = abs(x1 - x0);
    int dy  = -abs(y1 - y0);
    int sx  = (x0 < x1) ? 1 : -1;
    int sy  = (y0 < y1) ? 1 : -1;
    int err = dx + dy;

    for (;;)
    {
        bsp_ssd1306_pixel(x0, y0, true);
        if ((x0 == x1) && (y0 == y1))
        {
            break;
        }
        int e2 = 2 * err;
        if (e2 >= dy) { err += dy; x0 += sx; }
        if (e2 <= dx) { err += dx; y0 += sy; }
    }
}

void bsp_ssd1306_circle(int cx, int cy, int r)
{
    int x = r;
    int y = 0;
    int err = 1 - r;

    while (x >= y)
    {
        bsp_ssd1306_pixel(cx + x, cy + y, true);
        bsp_ssd1306_pixel(cx + y, cy + x, true);
        bsp_ssd1306_pixel(cx - y, cy + x, true);
        bsp_ssd1306_pixel(cx - x, cy + y, true);
        bsp_ssd1306_pixel(cx - x, cy - y, true);
        bsp_ssd1306_pixel(cx - y, cy - x, true);
        bsp_ssd1306_pixel(cx + y, cy - x, true);
        bsp_ssd1306_pixel(cx + x, cy - y, true);
        y++;
        if (err < 0)
        {
            err += 2 * y + 1;
        }
        else
        {
            x--;
            err += 2 * (y - x) + 1;
        }
    }
}

void bsp_ssd1306_char(int x, int y, char c)
{
    uint8_t uc = (uint8_t)c;
    if ((uc < 0x20U) || (uc > 0x7FU))
    {
        uc = (uint8_t)'?';
    }
    const uint8_t *glyph = s_font[uc - 0x20U];

    for (int col = 0; col < BSP_SSD1306_CHAR_W; col++)
    {
        uint8_t bits = (col < 5) ? glyph[col] : 0x00U; /* 6a coluna = espaco */
        for (int row = 0; row < BSP_SSD1306_CHAR_H; row++)
        {
            bsp_ssd1306_pixel(x + col, y + row, ((bits >> row) & 1U) != 0U);
        }
    }
}

void bsp_ssd1306_string(int x, int y, const char *s)
{
    while (*s != '\0')
    {
        bsp_ssd1306_char(x, y, *s++);
        x += BSP_SSD1306_CHAR_W;
    }
}

bool bsp_ssd1306_update(void)
{
    bool ok = true;
    for (uint8_t p = 0U; p < PAGES; p++)
    {
        ok = send_page(p) && ok;
    }
    s_page = 0U;
    return ok;
}

bool bsp_ssd1306_update_step(void)
{
    (void)send_page(s_page);   /* falhas ficam em bsp_i2c_error_count() */
    s_page++;
    if (s_page >= PAGES)
    {
        s_page = 0U;
        return true;
    }
    return false;
}

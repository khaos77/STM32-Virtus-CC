#define CTRL_CMD   0x00U /**< Byte de controle: os proximos bytes sao comandos */
#define CTRL_DATA  0x40U /**< Byte de controle: os proximos bytes sao dados    */
#define PAGES      (BSP_SSD1306_HEIGHT / 8)

/** @brief Framebuffer: s_fb[pagina][coluna], bit 0 = linha superior da pagina. */
static uint8_t s_fb[PAGES][BSP_SSD1306_WIDTH];
/** @brief Proxima pagina a ser enviada por @ref bsp_ssd1306_update_step. */
static uint8_t s_page;

/** @brief Sequencia de inicializacao (modulo 128x64 com charge pump interno). */
static const uint8_t s_init_seq[] = {
    0xAE,       /* display OFF                                   */
    0xD5, 0x80, /* divisor de clock / frequencia do oscilador    */
    0xA8, 0x3F, /* multiplex ratio = 64 linhas                   */
    0xD3, 0x00, /* display offset = 0                            */
    0x40,       /* linha inicial = 0                             */
    0x8D, 0x14, /* habilita o charge pump                        */
    0x20, 0x02, /* modo de enderecamento por pagina              */
    0xA1,       /* remapeia colunas (coluna 127 -> SEG0)         */
    0xC8,       /* varredura COM invertida (imagem "em pe")      */
    0xDA, 0x12, /* configuracao dos pinos COM                    */
    0x81, 0xCF, /* contraste                                     */
    0xD9, 0xF1, /* periodo de pre-carga                          */
    0xDB, 0x40, /* nivel de VCOMH                                */
    0xA4,       /* exibe o conteudo da RAM                       */
    0xA6,       /* modo normal (nao invertido)                   */
    0x2E,       /* desliga scroll                                */
    0xAF        /* display ON                                    */
};

